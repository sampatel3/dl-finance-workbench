/**
 * Regenerate `lib/narration.generated.ts`.
 *
 * Runs as the first half of `pnpm build`, so a deploy always ships prose written from the
 * data that deploy contains. Run it by hand after changing the seed, a rate or the detector.
 *
 * The one behaviour worth stating: **with no key this script leaves the committed file
 * alone.** Regenerating keyless would replace a model's sentences with the template
 * fallback, so every keyless build — CI's, a contributor's — would quietly downgrade the
 * demo's prose and show up as a diff nobody asked for. Keyless builds ship what is
 * committed, which is the whole reason the file is committed. The only exception is a file
 * that does not exist yet: then the fallback is written so the app compiles.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { liveClient } from '../lib/anthropic.ts';
import { buildBriefs, type BriefRecord } from '../lib/narration.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const TARGET = resolve(HERE, '../lib/narration.generated.ts');

const HEADER = `/**
 * GENERATED by \`pnpm narrate\` — do not edit.
 *
 * The figures here came from the seed and the prose came from a model. \`narration.test.ts\`
 * compares the pinned projection of this file against a fresh run, so a change to the seed,
 * a rate or the detector fails the test until this is regenerated.
 */

import type { BriefRecord } from './narration';

export const NARRATION: Readonly<Record<string, BriefRecord>> = `;

function render(briefs: Record<string, BriefRecord>): string {
  return `${HEADER}${JSON.stringify(briefs, null, 2)};\n`;
}

async function main(): Promise<void> {
  const client = await liveClient();

  if (client === undefined) {
    if (existsSync(TARGET)) {
      console.log('[narrate] no ANTHROPIC_API_KEY — keeping the committed narration.');
      return;
    }
    console.log('[narrate] no ANTHROPIC_API_KEY and no committed file — writing the fallback.');
  }

  const briefs = await buildBriefs({
    ...(client === undefined ? {} : { client }),
    onReject: (reason, detail) => console.warn(`[narrate] rejected (${reason}): ${detail}`),
  });

  await mkdir(dirname(TARGET), { recursive: true });
  await writeFile(TARGET, render(briefs), 'utf8');

  for (const [key, record] of Object.entries(briefs)) {
    console.log(`[narrate] ${key}: ${record.narration.narratedBy} — ${record.narration.headline}`);
  }
}

await main();
